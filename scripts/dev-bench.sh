#!/usr/bin/env bash
# Prepare the scratch configuration the daemon runs against during
# development: a lotor that starts on any laptop, with no radio, no
# root and no systemd. It is a bench, not a deployment — everything it
# writes lives under .dev/, which git ignores.
#
# The bench is deliberately not empty. A daemon with nothing declared
# has nothing to say, and every surface that reads it — the console,
# the web UI, the event bus — shows an empty room. So it declares one
# relay whose radio is absent, which is the degraded state those
# surfaces must render honestly and the one a developer without
# hardware would otherwise never see, and one station, which reaches
# `running` with no hardware at all.
#
# The database survives across runs on purpose: whatever you change
# through the console stays, and the bench is yours to shape. Run
# `task dev:reset` to start over.
set -euo pipefail
cd "$(dirname "$0")/.."

bench=".dev"
db="$bench/lotor.db"
mkdir -p "$bench"

if [ -f "$db" ]; then
	echo "bench: $db already exists — leaving it alone"
	exit 0
fi

# Minted per bench rather than committed: a private key in the
# repository is a private key on every fork, and these cost nothing to
# regenerate.
identity() { go run ./cmd/lotor identity new | awk '/^identity:/ {print $2}'; }
relay_id="$(identity)"
station_id="$(identity)"

cat > "$bench/config.yaml" <<YAML
# Generated by scripts/dev-bench.sh. Edit the script, not this file:
# the bench is rebuilt from scratch whenever .dev/ is removed.
cli:
  socket: $PWD/$bench/console.sock
# Bare on purpose: the address comes from config.DefaultWebListen, so
# the bench follows the code rather than restating it.
web:
radios:
  bench:
    driver: sx126x-spi
    profile: rak6421-13300x-slot1
    overrides:
      rak6421-13300x-slot1:
        # No such device, and that is the point: the relay below shows
        # what a radio that will not open looks like.
        spi: $PWD/$bench/absent-spi
relays:
  bench:
    protocol: meshcore
    radio: bench
    profile: eu-868-narrow
    overrides:
      eu-868-narrow:
        identity: $relay_id
        node_name: Bench
    tx:
      mode: dry
stations:
  bench:
    protocol: meshcore
    listen: 127.0.0.1:5000
    profile: eu-868-narrow
    overrides:
      eu-868-narrow:
        identity: $station_id
    tx:
      mode: dry
YAML

go run ./cmd/lotor config import "$bench/config.yaml" --db "$db"

# Asked of the toolchain rather than written here: a port spelled in
# two places is a port that will disagree with itself.
web="$(go doc ./internal/config DefaultWebListen | sed -n 's/.*= "\(.*\)"/\1/p')"
echo "bench: ready — web on http://$web, console at $bench/console.sock"
